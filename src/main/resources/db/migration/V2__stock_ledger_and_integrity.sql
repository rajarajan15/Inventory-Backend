ALTER TABLE products ADD COLUMN version BIGINT DEFAULT 0 NOT NULL;

-- Every session belongs to a user (the old one-token-per-user column allowed NULL).
DELETE FROM refresh_tokens WHERE user_id IS NULL;
ALTER TABLE refresh_tokens ALTER COLUMN user_id SET NOT NULL;

