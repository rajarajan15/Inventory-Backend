-- Stock ledger: one row per change to a product's quantity. Product and user details are copied onto the row,
-- so the history stays readable after a product is deleted or a user is removed.
CREATE TABLE stock_movements (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id   BIGINT       NOT NULL,
    product_id        BIGINT,
    product_sku       VARCHAR(255) NOT NULL,
    product_name      VARCHAR(255) NOT NULL,
    type              VARCHAR(20)  NOT NULL,
    quantity_change   INTEGER      NOT NULL,
    quantity_after    INTEGER      NOT NULL,
    notes             VARCHAR(500),
    performed_by_id   BIGINT,
    performed_by_name VARCHAR(255),
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_stock_movements_organization FOREIGN KEY (organization_id) REFERENCES organizations (id),
    CONSTRAINT fk_stock_movements_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE SET NULL,
    CONSTRAINT fk_stock_movements_user FOREIGN KEY (performed_by_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT stock_movements_type_check CHECK (type IN ('INITIAL', 'STOCK_IN', 'STOCK_OUT', 'ADJUSTMENT', 'IMPORT'))
);
CREATE INDEX idx_stock_movements_product ON stock_movements (organization_id, product_id, created_at);
